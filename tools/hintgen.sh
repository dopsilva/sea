# tools/hints.txt (key TAB hint) as a C table or as a Sea module:
#   sh tools/hintgen.sh c   tools/hints.txt > gen/sea_hints.h
#   sh tools/hintgen.sh sea tools/hints.txt > gen/hints.sea
mode=$1
awk -F'\t' -v mode="$mode" '
function esc(s) { gsub(/\\/, "\\\\", s); gsub(/"/, "\\\"", s); return s }
BEGIN {
    if (mode == "c") {
        print "/* Generated by tools/hintgen.sh from tools/hints.txt: do not edit. */"
        print "static const struct { const char *key, *hint; } SEA_HINTS[] = {"
    }
    else { print "-- Generated by tools/hintgen.sh from tools/hints.txt: do not edit."; print "local H = {}" }
}
/^#/ || NF < 2 { next }
{
    if (mode == "c") printf "    { \"%s\", \"%s\" },\n", esc($1), esc($2)
    else printf "H[\"%s\"] = \"%s\"\n", esc($1), esc($2)
}
END { if (mode == "c") print "};"; else print "return H" }' "$2"
