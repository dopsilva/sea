/*
 * Generates src/sea_unicode.h: the code point ranges of the letters (L), upper case
 * letters (Lu) and lower case letters (Ll) that `\p{L}`, `\p{Lu}`, `\p{Ll}` of the re
 * module match. The data comes from the C library's wide character classes in the
 * C.UTF-8 locale, so the header is committed and the build does not depend on it.
 *
 *   cc -o /tmp/genunicode tools/genunicode.c && /tmp/genunicode > src/sea_unicode.h
 */
#include <locale.h>
#include <stddef.h>
#include <stdio.h>
#include <wctype.h>

static void emit(const char *name, int (*is)(wint_t)) {
    printf("static const uint32_t %s[][2] = {\n", name);
    long lo = -1;
    for (long c = 0; c <= 0x110000; c++) {
        int yes = c < 0x110000 && !(c >= 0xD800 && c <= 0xDFFF) && is((wint_t)c);
        if (yes && lo < 0) lo = c;
        if (!yes && lo >= 0) {
            printf("    {0x%lX, 0x%lX},\n", lo, c - 1);
            lo = -1;
        }
    }
    printf("};\n\n");
}

/* The first digit of each run of ten decimal digits (Nd) outside ASCII. */
static const long ND_START[] = {0x660, 0x6F0, 0x7C0, 0x966, 0x9E6, 0xA66, 0xAE6, 0xB66, 0xBE6, 0xC66,
    0xCE6, 0xD66, 0xDE6, 0xE50, 0xED0, 0xF20, 0x1040, 0x1090, 0x17E0, 0x1810, 0x1946, 0x19D0, 0x1A80,
    0x1A90, 0x1B50, 0x1BB0, 0x1C40, 0x1C50, 0xA620, 0xA8D0, 0xA900, 0xA9D0, 0xA9F0, 0xAA50, 0xABF0,
    0xFF10};

static int is_nd(wint_t c) {
    if (c >= '0' && c <= '9') return 1;
    for (size_t i = 0; i < sizeof ND_START / sizeof *ND_START; i++)
        if ((long)c >= ND_START[i] && (long)c < ND_START[i] + 10) return 1;
    return 0;
}

static int is_l(wint_t c) { return iswalpha(c) && !is_nd(c); }
static int is_lu(wint_t c) { return iswupper(c); }
static int is_ll(wint_t c) { return iswlower(c); }

int main(void) {
    if (!setlocale(LC_ALL, "C.UTF-8") && !setlocale(LC_ALL, "C.utf8")) {
        fprintf(stderr, "no C.UTF-8 locale\n");
        return 1;
    }
    printf("/*\n * Copyright (c) 2026 The Sea Authors\n * SPDX-License-Identifier: BSD-3-Clause\n */\n\n");
    printf("/* Generated by tools/genunicode.c from the C library's character classes: do not edit. */\n\n");
    emit("SEA_UNI_L", is_l);
    emit("SEA_UNI_LU", is_lu);
    emit("SEA_UNI_LL", is_ll);
    emit("SEA_UNI_ND", is_nd);
    return 0;
}
