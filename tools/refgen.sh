# Turn the API tables of docs/reference.md ("| `name` | `signature` | description |")
# into a Sea module, sea/ref: a list of [name, signature, description] that
# `sea doc` prints for the built-in modules.
#   sh tools/refgen.sh docs/reference.md > gen/ref.sea
echo "-- Generated by tools/refgen.sh from docs/reference.md: do not edit."
echo "local R = []"
awk -F'|' '
function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
function unbt(s) { s = trim(s); if (s ~ /^`.*`$/) s = substr(s, 2, length(s) - 2); return s }
function esc(s) { gsub(/\\\|/, "|", s); gsub(/\\/, "\\\\", s); gsub(/"/, "\\\"", s); return s }
/^\| `/ {
    # a "\|" inside a cell is a literal bar: protect it while splitting
    line = $0
    gsub(/\\\|/, "\001", line)
    n = split(line, c, "|")
    if (n != 5) next
    key = unbt(c[2]); sig = unbt(c[3]); desc = trim(c[4])
    gsub(/\001/, "|", key); gsub(/\001/, "|", sig); gsub(/\001/, "|", desc)
    if (key !~ /^[A-Za-z_][A-Za-z0-9_.:]*$/) next
    printf "R[] = [\"%s\", \"%s\", \"%s\"]\n", esc(key), esc(sig), esc(desc)
}' "$1"
echo "return R"
